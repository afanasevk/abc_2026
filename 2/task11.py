#  времени года ("зима", "весна" и т.д.).

month = int(input())
if month > 12:
    print("error")
    exit()

if 3 <= month <= 5:
    print("Spring")
elif 6 <= month <= 8:
    print("Summer")
elif 9 <= month <= 11:
    print("Autumn")
else:
    print("Winter")

